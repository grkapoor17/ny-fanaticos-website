/**
 * Match data model. `lineup` and `scorers` use player names as recorded on
 * matchday, not player IDs — several names are one-off call-ups who never
 * joined the roster in players.ts. That's intentional: match history stays
 * complete even for players who aren't part of the featured squad. Assists
 * aren't tracked (not recorded reliably), so there's no `assisters` field.
 *
 * Designed to support multiple competitions/seasons so this can move to a
 * database later without changing the shape consumers rely on.
 */

export type MatchStatus = "scheduled" | "final";

export type Scorer = {
  name: string;
  goals: number;
};

export type Match = {
  id: string;
  competition: string;
  stage: string;
  season: string;
  date: string | null; // ISO date, or null when TBD
  time: string | null;
  venue: string | null;
  opponent: string;
  homeAway: "home" | "away" | "neutral" | null;
  nyFanaticosScore: number | null;
  opponentScore: number | null;
  penaltiesFor: number | null;
  penaltiesAgainst: number | null;
  status: MatchStatus;
  note?: string;
  /** Everyone who played, by name as recorded on matchday. */
  lineup?: string[];
  /** Only players with at least one goal. */
  scorers?: Scorer[];
};

